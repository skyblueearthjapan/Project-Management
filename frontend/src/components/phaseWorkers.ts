/**
 * 指定された工程 (short_label) で押印可能な作業員名のリストを返す。
 * 未定義の工程の場合は `null` (全員許可) を返す — 既存運用との互換性のため。
 */
export function workersForPhase(shortLabel: string): readonly string[] | null {
  return PHASE_WORKERS[shortLabel] ?? null;
}
